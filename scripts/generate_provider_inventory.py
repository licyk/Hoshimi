def cell(value: str, *, code: bool = False) -> str:
    """A table cell that MDX reads as text: code keeps braces literal; elsewhere they are escaped."""
    value = value.replace("|", "\\|")
    if not value:
        return ""
    if code:
        return f"`{value}`"
    return value.replace("{", "\\{").replace("}", "\\}").replace("<", "&lt;")


def page(locale: str) -> str:
    intro = INTRO[locale]
    lines = [
        "---",
        f'title: "{intro["title"]}"',
        f'description: "{intro["description"]}"',
        "icon: Table",
        "---",
        "",
        "{/* Generated by scripts/generate_provider_inventory.py. Do not edit. */}",
        "",
    ]
    for paragraph in intro["body"]:
        lines += [paragraph, ""]
    lines.append("| " + " | ".join(intro["columns"]) + " |")
    lines.append("| " + " | ".join("---" for _ in intro["columns"]) + " |")
    for d in SOURCE_PROVIDERS:
        values = (
            cell(d.source), cell(d.source_id, code=True), cell(d.id, code=True), cell(d.base_url, code=True), cell(d.protocol),
            cell(", ".join(d.auth)), cell(d.plan), cell(d.catalog), cell(d.coverage), cell(d.notes),
        )
        lines.append("| " + " | ".join(values) + " |")
    return "\n".join(lines) + "\n"


def main() -> None:
    DOCS.mkdir(parents=True, exist_ok=True)
    (DOCS / "providers-inventory.mdx").write_text(page("zh-CN"), encoding="utf-8")
    (DOCS / "providers-inventory.en.mdx").write_text(page("en"), encoding="utf-8")


if __name__ == "__main__":
    main()
