"""LobsterAI (有道龙虾): a loopback callback, then an auth-code exchange.

The portal link lands on a throwaway local server with ``?code=&state=``;
the code goes straight to ``/api/auth/exchange`` on the API host. No PKCE, no
DPoP — the exchange takes the code and five fields and answers with tokens.

``uuid`` and ``firstKeyfrom`` are generated by the client here and must travel
with the account forever: the refresh body re-sends them, so losing either
breaks renewal.
"""

from __future__ import annotations

import hashlib
import time
import uuid as _uuid
from collections.abc import Callable
from typing import Any

import httpx

from hoshimi.core.login.common import LOGIN_TIMEOUT_SECONDS, CallbackServer, LoginError, LoginReporter

PORTAL_BASE = "https://lobsterai.youdao.com"
API_BASE = "https://lobsterai-server.youdao.com"
EXCHANGE_PATH = "/api/auth/exchange"
CALLBACK_PATH = "/auth/callback"
USER_AGENT = "LobsterAI/0.1.0"
# The upstream resolves this live and caches it; we ship the pinned value the
# provider already uses so the exchange and the check-in speak one version.
CLIENT_VERSION = "2026.9.4"


def _login_url(port: int, state: str) -> str:
    """The portal link: a fragment route, so the query cannot use URL(params=)."""
    redirect_uri = f"http://127.0.0.1:{port}{CALLBACK_PATH}"
    from urllib.parse import quote

    return (
        f"{PORTAL_BASE}/portal#/login?source=electron"
        f"&redirect_uri={quote(redirect_uri, safe='')}&state={quote(state, safe='')}"
    )


def _uid_of(payload: dict[str, Any], access_token: str) -> str:
    """Four-level fallback for the account id; the hash keeps empty ones distinct."""
    raw_user = payload.get("user")
    user = raw_user if isinstance(raw_user, dict) else {}
    for key in ("id", "userId", "yid"):
        value = user.get(key)
        if isinstance(value, str) and value:
            return value
    return hashlib.sha256(access_token.encode("utf-8")).hexdigest()[:16]


def start_lobsterai_login(client: httpx.Client, report: Callable[[str], None]) -> dict[str, Any]:
    state = _uuid.uuid4().hex
    session_uuid = _uuid.uuid4().hex
    first_keyfrom = str(int(time.time() * 1000))

    server = CallbackServer(CALLBACK_PATH)
    try:
        report(_login_url(server.port, state))
        params = report.authorization(server) if isinstance(report, LoginReporter) else server.wait(LOGIN_TIMEOUT_SECONDS)
    finally:
        server.close()

    code = params.get("code") or ""
    if not code:
        # The portal reports a refusal through `error` rather than a code.
        detail = params.get("error") or "the callback carried no code"
        raise LoginError(f"lobsterai: authorization did not complete ({detail})")
    if params.get("state") != state:
        raise LoginError("lobsterai: the callback did not match this login (state mismatch)")

    latest_keyfrom = str(int(time.time() * 1000))
    try:
        response = client.post(
            f"{API_BASE}{EXCHANGE_PATH}",
            json={
                "authCode": code,
                "firstKeyfrom": first_keyfrom,
                "latestKeyfrom": latest_keyfrom,
                "uuid": session_uuid,
                "version": CLIENT_VERSION,
            },
            headers={
                "Accept": "application/json",
                "Content-Type": "application/json",
                "User-Agent": USER_AGENT,
            },
            timeout=30.0,
        )
    except httpx.HTTPError as exc:
        raise LoginError(f"lobsterai: the code exchange failed: {exc}") from exc
    try:
        payload = response.json()
    except ValueError:
        raise LoginError(f"lobsterai: the exchange response was not JSON (HTTP {response.status_code})") from None
    if not isinstance(payload, dict) or payload.get("code") != 0:
        message = str(payload.get("msg") or payload.get("message") or f"HTTP {response.status_code}") if isinstance(payload, dict) else f"HTTP {response.status_code}"
        raise LoginError(f"lobsterai: the code exchange failed: {message}")
    data = payload.get("data")
    if not isinstance(data, dict):
        raise LoginError("lobsterai: the exchange response had no data")
    access = str(data.get("accessToken") or "")
    if not access:
        raise LoginError("lobsterai: the exchange returned no access token")

    credential: dict[str, Any] = {
        "access_token": access,
        "uuid": session_uuid,
        "first_keyfrom": first_keyfrom,
        # Kept at the login instant on purpose: the station treats it as the
        # session's birth mark, and renewal re-sends it verbatim.
        "latest_keyfrom": latest_keyfrom,
        "uid": _uid_of(data, access),
    }
    refresh = data.get("refreshToken")
    if isinstance(refresh, str) and refresh:
        credential["refresh_token"] = refresh
    expires_in = data.get("expiresIn")
    if isinstance(expires_in, (int, float)) and not isinstance(expires_in, bool) and expires_in > 0:
        credential["expires_at"] = str(int((time.time() + expires_in) * 1000))
    user = data.get("user") if isinstance(data.get("user"), dict) else {}
    user_id = user.get("userId")
    if isinstance(user_id, str) and user_id:
        credential["user_id"] = user_id
    nickname = user.get("nickname")
    if isinstance(nickname, str) and nickname:
        credential["nickname"] = nickname
    return credential
